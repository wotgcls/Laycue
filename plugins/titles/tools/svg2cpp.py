#!/usr/bin/env python3
"""Turns the brand icons in data/brand-icons/*.svg (Simple Icons, CC0) into src/render/brand-icons-data.inc.

Why a generated file: drawing the icons with plain QPainterPath needs no extra Qt module (QtSvg) and no
SVG parser inside OBS. Each icon is one path in a 24 x 24 box; arcs become cubic curves here.
Needs fontTools (pip install fonttools). Run from the repo root:  python3 plugins/titles/tools/svg2cpp.py
"""
import re, sys, pathlib
from fontTools.svgLib.path import parse_path
from fontTools.pens.recordingPen import RecordingPen

root = pathlib.Path(__file__).resolve().parent.parent
names = ["youtube", "instagram", "tiktok", "facebook"]
out = ["// Generated by tools/svg2cpp.py from data/brand-icons/*.svg (Simple Icons, CC0). Do not edit.\n"]
for name in names:
    svg = (root / "data/brand-icons" / f"{name}.svg").read_text()
    d = re.search(r'<path d="([^"]+)"', svg).group(1)
    pen = RecordingPen()
    parse_path(d, pen)
    out.append(f"static const IconSeg k_{name}[] = {{\n")
    for op, pts in pen.value:
        flat = [c for p in pts for c in p]
        if op == "moveTo":   out.append(f"\t{{'M', {{{flat[0]:.4f}f, {flat[1]:.4f}f}}}},\n")
        elif op == "lineTo": out.append(f"\t{{'L', {{{flat[0]:.4f}f, {flat[1]:.4f}f}}}},\n")
        elif op == "curveTo":out.append("\t{'C', {" + ", ".join(f"{v:.4f}f" for v in flat) + "}},\n")
        elif op == "qCurveTo":
            # quadratic with possibly several off-curve points: fontTools gives them already split to one control + end
            out.append("\t{'Q', {" + ", ".join(f"{v:.4f}f" for v in flat) + "}},\n")
        elif op in ("closePath", "endPath"): out.append("\t{'Z', {}},\n")
    out.append("};\n")
(root / "src/render/brand-icons-data.inc").write_text("".join(out))
print("wrote", root / "src/render/brand-icons-data.inc")
